    /// <summary>
    /// Unity Remote Config REST API에서 설정값 가져오기
    /// </summary>
    private static async Task<RemoteConfigExport> FetchRemoteConfig()
    {
        try
        {
            using var client = new HttpClient();
            client.DefaultRequestHeaders.Add("Authorization", AuthHeader);
            
            string url = $"https://services.api.unity.com/remote-config/v1/projects/{ProjectId}/environments/{EnvironmentId}/configs";
            
            var response = await client.GetAsync(url);
            
            if (!response.IsSuccessStatusCode)
            {
                Debug.LogWarning($"[Balance Exporter] Remote Config fetch 실패: {response.StatusCode}");
                return GetDefaultRemoteConfig();
            }

            string jsonResponse = await response.Content.ReadAsStringAsync();
            var configsArray = JObject.Parse(jsonResponse)["configs"] as JArray;
            
            if (configsArray == null || configsArray.Count == 0)
            {
                Debug.LogWarning("[Balance Exporter] Remote Config에 설정이 없습니다.");
                return GetDefaultRemoteConfig();
            }

            // 첫 번째 config의 value들 파싱
            var configValues = configsArray[0]["value"] as JArray;
            var result = new RemoteConfigExport();
            
            foreach (var item in configValues)
            {
                string key = item["key"]?.ToString();
                string value = item["value"]?.ToString();
                
                switch (key)
                {
                    case "REINFORCE_VALUE_GOLD":
                        var reinforceDict = JsonConvert.DeserializeObject<Dictionary<string, ReinforceRule>>(value);
                        if (reinforceDict.TryGetValue("Power", out var power)) result.reinforcePower = power;
                        if (reinforceDict.TryGetValue("MaxHp", out var maxHp)) result.reinforceMaxHp = maxHp;
                        if (reinforceDict.TryGetValue("CritDmg", out var critDmg)) result.reinforceCritDmg = critDmg;
                        break;
                    case "GOLD_DROP_FORMULA":
                        result.goldDropFormula = value;
                        break;
                    case "EXP_DROP_FORMULA":
                        result.expDropFormula = value;
                        break;
                }
            }
            
            // 승급 기본값 (Remote Config에 없으면)
            result.promoteRanks = result.promoteRanks ?? new PromoteInfo[]
            {
                new PromoteInfo { rank = "Stone", mult = 1f, unlockStage = 1 },
                new PromoteInfo { rank = "Bronze", mult = 1.5f, unlockStage = 30 },
                new PromoteInfo { rank = "Iron", mult = 3f, unlockStage = 60 },
                new PromoteInfo { rank = "Silver", mult = 8f, unlockStage = 120 },
                new PromoteInfo { rank = "Gold", mult = 15f, unlockStage = 200 }
            };

            Debug.Log("[Balance Exporter] Remote Config 가져오기 성공!");
            return result;
        }
        catch (System.Exception e)
        {
            Debug.LogError($"[Balance Exporter] Remote Config 오류: {e.Message}");
            return GetDefaultRemoteConfig();
        }
    }

    private static RemoteConfigExport GetDefaultRemoteConfig()
    {
        return new RemoteConfigExport
        {
            reinforcePower = new ReinforceRule { baseInc = 1f, step = 100, stepInc = 0.5f, startValue = 10f },
            reinforceMaxHp = new ReinforceRule { baseInc = 4f, step = 100, stepInc = 1f, startValue = 100f },
            reinforceCritDmg = new ReinforceRule { baseInc = 0.01f, step = 100, stepInc = 0.01f, startValue = 1.2f },
            goldDropFormula = "",
            expDropFormula = "",
            promoteRanks = new PromoteInfo[]
            {
                new PromoteInfo { rank = "Stone", mult = 1f, unlockStage = 1 },
