    [System.Serializable]
    public class RemoteConfigExport
    {
        // 강화 공식
        public ReinforceRule reinforcePower;
        public ReinforceRule reinforceMaxHp;
        public ReinforceRule reinforceCritDmg;
        
        // 골드/EXP 드랍 공식 (스테이지 기반)
        public string goldDropFormula;
        public string expDropFormula;
        
        // 승급 배율
        public PromoteInfo[] promoteRanks;
    }

    [System.Serializable]
    public class ReinforceRule
    {
        public float baseInc;
        public int step;
        public float stepInc;
        public float startValue;
    }

    [System.Serializable]
