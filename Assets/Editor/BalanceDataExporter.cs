                new PromoteInfo { rank = "Silver", mult = 8f, unlockStage = 120 },
                new PromoteInfo { rank = "Gold", mult = 15f, unlockStage = 200 }
            }
        };
    }

    private static List<WeaponExport> ExportWeapons()
    {
        var list = new List<WeaponExport>();
        string[] guids = AssetDatabase.FindAssets("t:WeaponData");

        foreach (string guid in guids)
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            WeaponData weapon = AssetDatabase.LoadAssetAtPath<WeaponData>(path);
            if (weapon == null) continue;

            // 무기 효과 변환
            var effects = new List<WeaponEffectExport>();
            if (weapon._weaponEffects != null)
            {
                foreach (var eff in weapon._weaponEffects)
                {
                    effects.Add(new WeaponEffectExport { skillType = (int)eff.type, skillTypeName = eff.type.ToString(), value = eff.value });
                }
            }
            
            list.Add(new WeaponExport
            {
                id = weapon.name,
                name = weapon.WeaponName,
                type = weapon.WeaponType.ToString(),
                rarity = weapon.WeaponRarity.ToString(),
                power = weapon.Power,
                critDamage = weapon.CriticalDamage,
                critical = weapon.Critical,
                attackSpeed = weapon.AttackSpeed,
                powerPerUpgrade = weapon.PowerPerUpgrade,
                critDmgPerUpgrade = weapon.CritDmgPerUpgrade,
                effects = effects
            });
        }

        return list;
    }

    private static List<SkillExport> ExportSkills()
    {
        var list = new List<SkillExport>();
        string[] guids = AssetDatabase.FindAssets("t:SkillData");

        foreach (string guid in guids)
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            SkillData skill = AssetDatabase.LoadAssetAtPath<SkillData>(path);
            if (skill == null) continue;

            list.Add(new SkillExport
            {
                id = skill.name,
                name = skill.skillName,
                type = skill.type.ToString(),
                rarity = skill.rarity.ToString(),
                isActive = skill.isActiveSkill,
                isPlayerSkill = skill.isPlayerSkill,
                cooltime = skill.cooltime,
                requireMp = skill.requireMp,
                values = skill.value.ToArray()
            });
        }

        return list;
    }

    private static List<StageExport> ExportStages()
    {
        var list = new List<StageExport>();
        string[] guids = AssetDatabase.FindAssets("t:StageInfo");

        foreach (string guid in guids)
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            StageInfo stage = AssetDatabase.LoadAssetAtPath<StageInfo>(path);
            if (stage == null) continue;

            list.Add(new StageExport
            {
                stageNum = stage.stageNum,
                name = stage.stageName,
                battleType = stage.battleType.ToString(),
                recommendLevel = stage.recommendLevel,
                enemyMaxHp = stage.enemyStatusFromStage?.maxHp ?? "",
                bossMaxHp = stage.bossStatusFromStage?.maxHp ?? "",
                bossResist = stage.bossStatusFromStage?.resist ?? 0f,
                bossPower = stage.bossStatusFromStage?.power ?? ""
            });
        }

        return list;
    }

    private static List<SkillAcquireExport> ExportSkillAcquire()
    {
        var list = new List<SkillAcquireExport>();
        string[] guids = AssetDatabase.FindAssets("t:SkillAcquireInfo");

        foreach (string guid in guids)
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            SkillAcquireInfo info = AssetDatabase.LoadAssetAtPath<SkillAcquireInfo>(path);
            if (info == null) continue;

            list.Add(new SkillAcquireExport
            {
                acquireLevel = info.acquireLevel,
                activeSkill = info.activeSkill != null ? info.activeSkill.name : "",
                passiveSkill = info.passiveSkill != null ? info.passiveSkill.name : ""
            });
        }

        return list;
    }

