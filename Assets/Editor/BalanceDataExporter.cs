    {
        public string bookId;
        public string[] weaponIds;
        public int[] upgradeLevels;   // 각 단계별 필요 등록 무기 수
        public float[] upgradeStats;  // 각 단계별 Power 보너스
    }

    private static List<WeaponBookExport> ExportWeaponBooks()
    {
        var list = new List<WeaponBookExport>();
        string[] guids = AssetDatabase.FindAssets("t:WeaponBookData");

        foreach (string guid in guids)
        {
            string path = AssetDatabase.GUIDToAssetPath(guid);
            WeaponBookData book = AssetDatabase.LoadAssetAtPath<WeaponBookData>(path);
            if (book == null) continue;

            var weaponIds = new List<string>();
            if (book.weapons != null)
            {
                foreach (var w in book.weapons)
                {
                    if (w != null) weaponIds.Add(w.name);
                }
            }

            list.Add(new WeaponBookExport
            {
                bookId = book.bookId,
                weaponIds = weaponIds.ToArray(),
                upgradeLevels = book.upgradeLevels,
                upgradeStats = book.upgradeStats
            });
        }

        return list;
    }
